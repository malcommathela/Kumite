import { createHash, randomUUID } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const REGISTRY_DIRECTORY = path.join('src', '.kumite-preview-registry');
const MODULE_DIRECTORY = 'modules';

export interface ArtifactPreviewRegistryModule {
    key: string;
    artifactHash: string;
    kind: string;
    name: string;
    source: string;
}
export interface ArtifactPreviewRegistryResult {
    manifestPath: string;
    indexPath: string;
    entrySources: Record<string, string>;
}
interface RegistryManifest {
    schemaVersion: 1;
    entries: Array<{ key: string; artifactHash: string; kind: string; name: string; module: string; moduleHash: string }>;
}
function sha256(value: string): string {
    return createHash('sha256').update(value).digest('hex');
}
async function writeGeneratedFile(file: string, contents: string): Promise<void> {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === contents) return;
    const temporary = `${file}.${randomUUID()}.tmp`;
    try {
        fs.writeFileSync(temporary, contents, { encoding: 'utf8', flag: 'wx' });
        const attempts = process.platform === 'win32' ? 5 : 1;
        for (let attempt = 0; ; attempt += 1) {
            try {
                fs.renameSync(temporary, file);
                break;
            } catch (error) {
                const code = (error as NodeJS.ErrnoException).code;
                if (attempt >= attempts - 1 || !['EPERM', 'EBUSY', 'EACCES'].includes(code ?? '') || !fs.existsSync(temporary)) throw error;
                await new Promise((resolve) => setTimeout(resolve, 30 * (attempt + 1)));
            }
        }
    } finally {
        if (fs.existsSync(temporary)) fs.rmSync(temporary, { force: true });
    }
}

/** Create isolated, lazy-loadable preview modules from already validated artifacts. */
export async function generateArtifactPreviewRegistry(
    workspaceRoot: string,
    modules: ArtifactPreviewRegistryModule[],
): Promise<ArtifactPreviewRegistryResult> {
    const root = path.join(workspaceRoot, REGISTRY_DIRECTORY);
    const sorted = [...modules].sort((a, b) => a.key.localeCompare(b.key));
    let existingEntries: RegistryManifest['entries'] = [];
    try {
        const previous = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8')) as RegistryManifest;
        if (previous.schemaVersion === 1 && Array.isArray(previous.entries)) existingEntries = previous.entries;
    } catch {
        existingEntries = [];
    }
    const entriesByKey = new Map(existingEntries.map((entry) => [entry.key, entry]));
    const entries: RegistryManifest['entries'] = [];
    const entrySources: Record<string, string> = {};
    const loaders: string[] = [];
    for (const item of sorted) {
        if (!item.key || !/^[a-f0-9]{64}$/.test(item.artifactHash) || !item.name.trim() || !item.source.trim()) {
            throw new Error(`Invalid generated preview registry entry "${item.name}".`);
        }
        const moduleId = sha256(item.key);
        const module = `modules/${moduleId}.tsx`;
        const moduleHash = sha256(item.source);
        await writeGeneratedFile(path.join(root, module), item.source);
        const entry = { key: item.key, artifactHash: item.artifactHash, kind: item.kind, name: item.name, module, moduleHash };
        entriesByKey.set(item.key, entry);
        entrySources[item.key] = `import { loadPreview } from '@/.kumite-preview-registry/index';\nvoid loadPreview(${JSON.stringify(item.key)});\n`;
    }
    entries.push(...entriesByKey.values());
    entries.sort((a, b) => a.key.localeCompare(b.key));
    loaders.push(...entries.map((entry) => `    ${JSON.stringify(entry.key)}: () => import('./${entry.module}'),`));
    const manifest: RegistryManifest = { schemaVersion: 1, entries };
    const index = [
        '// Generated by Kumite. Do not edit.',
        'const loaders: Record<string, () => Promise<unknown>> = {',
        ...loaders,
        '};',
        'export function loadPreview(key: string): Promise<unknown> {',
        '    const load = loaders[key];',
        '    if (!load) return Promise.reject(new Error(`Unknown preview registry key: ${key}`));',
        '    return load();',
        '}',
        '',
    ].join('\n');
    await writeGeneratedFile(path.join(root, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
    await writeGeneratedFile(path.join(root, 'index.ts'), index);
    return { manifestPath: path.join(root, 'manifest.json'), indexPath: path.join(root, 'index.ts'), entrySources };
}
